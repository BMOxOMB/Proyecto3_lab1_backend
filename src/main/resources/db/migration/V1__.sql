ALTER TABLE rol
    ADD CONSTRAINT uc_rol_rol UNIQUE (rol);

ALTER TABLE usuario
    ADD CONSTRAINT uc_usuario_username UNIQUE (username);

ALTER TABLE producto
    ADD CONSTRAINT FK_PRODUCTO_ON_CATEGORIA FOREIGN KEY (categoria_id) REFERENCES categoria (id);

ALTER TABLE revchanges
    ADD CONSTRAINT fk_revchanges_on_default_tracking_modified_entities_changelog FOREIGN KEY (rev) REFERENCES revinfo (rev);

ALTER TABLE usuario_roles
    ADD CONSTRAINT fk_usurol_on_rol FOREIGN KEY (rol_id) REFERENCES rol (id);

ALTER TABLE usuario_roles
    ADD CONSTRAINT fk_usurol_on_usuario FOREIGN KEY (usuario_id) REFERENCES usuario (id);